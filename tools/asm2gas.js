#!/usr/bin/env node
// asm2gas.js
// Translates the ARM Thumb assembly that MakeCode writes (built/rpi/binary.asm,
// in MakeCode's own assembler dialect) into standard GNU assembler syntax that
// devkitARM's arm-none-eabi-as accepts.
//
// Usage:  node tools/asm2gas.js <binary.asm> <out.s> [imports.json]
//
// The output is one section, ".pxt_user", starting at the label
// pxt_user_start. Every MakeCode runtime function or object the game needs
// (e.g. "numops::adds") becomes an undefined symbol named pxt_numops__adds,
// to be supplied by the 3DS runtime at link time. imports.json lists them.

const fs = require("fs");

const REGS = /^(r\d+|sp|lr|pc)$/i;

// Removes a trailing ";" comment, leaving ";" inside quoted strings alone.
function stripComment(line) {
    let inStr = false;
    for (let i = 0; i < line.length; i++) {
        const c = line[i];
        if (inStr) {
            if (c === "\\") i++;
            else if (c === '"') inStr = false;
        } else if (c === '"') inStr = true;
        else if (c === ";") return line.slice(0, i);
    }
    return line;
}

// Same string rules as MakeCode's assembler.
function parseString(s) {
    s = s.replace(/\\\\/g, "\\B")
        .replace(/\\(['\?])/g, (f, q) => q)
        .replace(/\\[z0]/g, "\u0000")
        .replace(/\\x([0-9a-f][0-9a-f])/gi, (f, h) => "\\u00" + h)
        .replace(/\\B/g, "\\\\");
    return JSON.parse(s);
}

function byteList(bytes) {
    const out = [];
    for (let i = 0; i < bytes.length; i += 24)
        out.push("    .byte " + bytes.slice(i, i + 24).join(","));
    return out;
}

function externName(name) {
    return "pxt_" + name.replace(/::/g, "__").replace(/[^\w]/g, "_");
}

function translate(text) {
    const rawLines = text.split(/\r?\n/);
    const lines = rawLines.map(stripComment);

    // Pass 1: find every label defined in the file, so anything else that
    // looks like a label is known to come from the runtime.
    const defined = new Set();
    for (const l of lines) {
        const m = /^\s*([.\w]+):/.exec(l);
        if (m && m[1][0] !== ".") defined.add(m[1]);
    }

    const out = [
        "@ Generated by tools/asm2gas.js - do not edit.",
        "    .syntax unified",
        "    .arch armv6k",
        "    .thumb",
        '    .section .pxt_user,"ax",%progbits',
        "    .balign 4, 0",
        "    .global pxt_user_start",
        "pxt_user_start:",
    ];
    const imports = new Map(); // original name -> symbol
    let scope = 0;             // MakeCode scopes ".name" labels to the current section
    let stack = 0;             // words pushed since the section began
    let marks = {};            // @stackmark name -> stack depth at that point

    const local = name => `.Ls${scope}_${name.slice(1).replace(/\./g, "_")}`;

    // Turns one label reference into its GNU form.
    function sym(name, isFn) {
        if (name[0] === ".") return local(name) + (isFn ? "+1" : "");
        if (defined.has(name)) return name + (isFn ? "+1" : "");
        // Runtime symbol. The linker sets the Thumb/ARM bit on function
        // addresses itself, so "@fn" needs nothing extra here.
        if (!imports.has(name)) imports.set(name, externName(name));
        return imports.get(name);
    }

    // Translates an operand or data value: numbers pass through, stack
    // references (locals@3) become byte offsets, labels are renamed.
    function value(tok, lineNo) {
        let m = /^(\w+)@(-?\d+)$/.exec(tok);
        if (m) {
            if (!(m[1] in marks)) throw new Error(`line ${lineNo}: unknown stack mark "${m[1]}"`);
            return String(4 * (stack - marks[m[1]] + parseInt(m[2])));
        }
        m = /^(.*)@fn$/.exec(tok);
        if (m) return sym(m[1], true);
        if (/^[-+]?(\d|0x)/i.test(tok)) return tok;
        m = /^([.\w:]+?)([-+|]1)?$/.exec(tok);
        if (m && /^[.a-zA-Z_]/.test(m[1])) return sym(m[1], false) + (m[2] || "");
        throw new Error(`line ${lineNo}: cannot translate "${tok}"`);
    }

    function newScope() {
        scope++;
        stack = 0;
        marks = {};
    }

    let afterCode = false; // was the last thing emitted an instruction?

    // Is the next statement (the rest of this line, or the lines after it) a
    // ".word" holding a label?
    function startsAddressTable(restOfLine, idx) {
        let t = restOfLine.trim();
        for (let i = idx + 1; !t && i < lines.length; i++) {
            const c = lines[i].trim();
            if (c && c[0] !== "@" && !c.startsWith(".object")) t = c;
        }
        return /^\.word\s+[.a-zA-Z_]/.test(t);
    }

    lines.forEach((raw, idx) => {
        const lineNo = idx + 1;
        let l = raw.trim();
        if (!l) return;


        const lab = /^([.\w]+):\s*(.*)$/.exec(l);
        if (lab) {
            // A few of MakeCode's hand-written helpers put a table of addresses
            // straight after code without aligning it. The 3DS program format
            // only allows addresses at 4-byte boundaries, so align those tables.
            if (afterCode && startsAddressTable(lab[2], idx)) out.push("    .balign 4, 0");
            out.push((lab[1][0] === "." ? local(lab[1]) : lab[1]) + ":");
            l = lab[2];
            if (!l) return;
        }

        const sp = l.search(/\s/);
        const op = (sp < 0 ? l : l.slice(0, sp));
        const rest = sp < 0 ? "" : l.slice(sp).trim();
        const args = () => rest.split(",").map(s => s.trim()).filter(s => s);

        if (op[0] === "@") {
            if (op === "@stackmark") marks[rest] = stack;
            else if (op === "@stackempty") {
                if (marks[rest] !== stack) throw new Error(`line ${lineNo}: stack mismatch for "${rest}"`);
            } else if (op === "@dummystack") stack += parseInt(rest);
            else if (op === "@scope") { scope++; }
            else if (op !== "@nostackcheck") throw new Error(`line ${lineNo}: unknown directive ${op}`);
            return;
        }

        if (op[0] === ".") {
            if (![".section", ".global", ".object", ".startaddr"].includes(op)) afterCode = false;
            switch (op) {
                case ".section": case ".global": newScope(); return;
                case ".object": case ".startaddr": return;
                case ".balign": out.push(`    .balign ${rest}, 0`); return;
                case ".short": case ".hword": out.push("    .short " + args().map(a => value(a, lineNo)).join(", ")); return;
                case ".word": out.push("    .word " + args().map(a => value(a, lineNo)).join(", ")); return;
                case ".byte": {
                    const a = args();
                    if (a.length % 2) a.push("0");
                    out.push("    .byte " + a.join(", "));
                    return;
                }
                case ".hex": {
                    // MakeCode emits this two bytes at a time, zero-padding a final odd byte in front.
                    const bytes = [];
                    for (const w of rest.split(/[\s,]+/).filter(s => s)) {
                        if (!/^[0-9a-f]*$/i.test(w)) throw new Error(`line ${lineNo}: bad .hex`);
                        for (let i = 0; i < w.length; i += 4) {
                            const n = parseInt(w.slice(i, i + 4), 16);
                            bytes.push((n >> 8) & 0xff, n & 0xff);
                        }
                    }
                    out.push(...byteList(bytes));
                    return;
                }
                case ".string": case ".ascii": case ".asciz": {
                    const s = parseString(rest);
                    const bytes = [];
                    for (let i = 0; i < s.length + 1; i += 2)
                        bytes.push((s.charCodeAt(i) || 0) & 0xff, (s.charCodeAt(i + 1) || 0) & 0xff);
                    out.push("    .balign 2, 0", ...byteList(bytes));
                    return;
                }
                default:
                    throw new Error(`line ${lineNo}: unsupported directive ${op}`);
            }
        }

        // ---- an instruction ----
        let mn = op.toLowerCase();

        // Track how much is on the stack, exactly as MakeCode's assembler does,
        // because "name@N" operands are relative to it.
        let stackDelta = 0;
        if (mn === "push" || mn === "pop") {
            const n = (/\{(.*)\}/.exec(rest) || ["", ""])[1].split(",").filter(s => s.trim()).length;
            stackDelta = mn === "push" ? n : -n;
        } else if ((mn === "add" || mn === "sub") && /^sp\s*,\s*#/i.test(rest)) {
            const n = Function(`"use strict"; return (${rest.replace(/^sp\s*,\s*#/i, "")});`)() / 4;
            stackDelta = mn === "add" ? -n : n;
        }

        // "bb" means "b, or bl if the target is too far". Any still left in the
        // file were too far, so they are bl.
        if (mn === "bb") mn = "bl";

        let operands = rest;
        if (/^(b|bl|beq|bne|bcs|bcc|bmi|bpl|bvs|bvc|bhi|bls|bge|blt|bgt|ble|bhs|blo|bal)$/.test(mn)) {
            operands = value(rest, lineNo);
        } else if (mn === "ldr" && /^r\d+\s*,\s*[^\[\s]/i.test(rest)) {
            const a = args();                       // ldr rX, label  (PC-relative load)
            operands = `${a[0]}, ${value(a[1], lineNo)}`;
        } else if (rest.includes("@")) {
            operands = rest.replace(/\w+@-?\d+/g, t => "#" + value(t, lineNo));
        }
        if (mn === "push" || mn === "pop") {
            // GNU as wants register lists in ascending order.
            const order = r => ({ sp: 13, lr: 14, pc: 15 })[r] ?? parseInt(r.slice(1));
            operands = operands.replace(/\{(.*)\}/, (f, inner) => "{" +
                inner.split(",").map(s => s.trim().toLowerCase()).filter(s => s)
                    .sort((a, b) => order(a) - order(b)).join(", ") + "}");
        }

        out.push(`    ${mn} ${operands}`.trimEnd());
        afterCode = true;
        stack += stackDelta;
    });

    out.push("    .balign 4, 0", "    .global pxt_user_end", "pxt_user_end:", "");
    return { gas: out.join("\n"), imports };
}

module.exports = { translate, externName };

if (require.main === module) {
    const [src, dst, importsPath] = process.argv.slice(2);
    if (!src || !dst) {
        console.error("Usage: node tools/asm2gas.js <binary.asm> <out.s> [imports.json]");
        process.exit(1);
    }
    const { gas, imports } = translate(fs.readFileSync(src, "utf8"));
    fs.writeFileSync(dst, gas);
    if (importsPath) fs.writeFileSync(importsPath, JSON.stringify(Object.fromEntries([...imports].sort()), null, 2) + "\n");
    console.log(`Wrote ${dst} (${imports.size} runtime symbols needed)`);
}
